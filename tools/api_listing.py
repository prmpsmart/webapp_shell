"""Writes `docs/API.md`: every public class, function and signature of the library, read from the source (nothing is
imported, so the optional toolkits are not needed). Run: `python tools/api_listing.py` (add `--check` to only compare).
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "src" / "webapp_shell"
TARGET = ROOT / "docs" / "API.md"
HEADER = """# API listing

Generated by `python tools/api_listing.py` from the source; do not edit by hand (a test fails when it is out of date).
Every public name (no leading underscore) of every module, with its signature. **Exported** means the name is in the
`__all__` of `webapp_shell` or of `webapp_shell.contract`, the two places a project imports from. The rest is public
only because it has no underscore: the owner decides which of those stay public and which are renamed with `_`.

"""


def exported_names(path: Path) -> set[str]:
    """The names in the `__all__` of one `__init__.py`."""
    for node in ast.parse(path.read_text()).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            return set(ast.literal_eval(node.value))
    return set()


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    if any(ast.unparse(decorator) == "property" for decorator in node.decorator_list):
        prefix = "property"
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"{prefix} {node.name}({ast.unparse(node.args)}){returns}"


def first_line(node: ast.AST) -> str:
    doc = (
        ast.get_docstring(node)
        if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef | ast.Module)
        else None
    )
    return " ".join(doc.strip().split("\n\n")[0].split()) if doc else ""  # the first paragraph, on one line


def is_public(name: str) -> bool:
    return not name.startswith("_")


def describe_class(node: ast.ClassDef) -> list[str]:
    bases = ", ".join(ast.unparse(base) for base in node.bases)
    lines = [f"- `class {node.name}({bases})`" if bases else f"- `class {node.name}`"]
    if summary := first_line(node):
        lines[0] += f" — {summary}"
    for member in node.body:
        if isinstance(member, ast.FunctionDef | ast.AsyncFunctionDef) and (
            is_public(member.name) or member.name == "__init__"
        ):
            lines.append(f"  - `{signature(member)}`")
        elif isinstance(member, ast.AnnAssign) and isinstance(member.target, ast.Name) and is_public(member.target.id):
            lines.append(f"  - `{member.target.id}: {ast.unparse(member.annotation)}`")
        elif isinstance(member, ast.Assign) and all(
            isinstance(t, ast.Name) and is_public(t.id) for t in member.targets
        ):
            lines.append(
                "  - `" + ", ".join(t.id for t in member.targets if isinstance(t, ast.Name)) + "`"
            )  # enum members
    return lines


def describe_module(path: Path, exported: set[str]) -> list[str]:
    lines: list[str] = []
    for node in ast.parse(path.read_text()).body:
        if isinstance(node, ast.ClassDef) and is_public(node.name):
            block = describe_class(node)
        elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and is_public(node.name):
            block = [f"- `{signature(node)}`" + (f" — {first_line(node)}" if first_line(node) else "")]
        elif isinstance(node, ast.TypeAlias) and isinstance(node.name, ast.Name) and is_public(node.name.id):
            block = [f"- `type {node.name.id} = {ast.unparse(node.value)}`"]
        else:
            continue
        name = (
            node.name.id
            if isinstance(node, ast.TypeAlias) and isinstance(node.name, ast.Name)
            else getattr(node, "name", "")
        )
        block[0] += " **(exported)**" if name in exported else ""
        lines.extend(block)
    return lines


def render() -> str:
    exported = exported_names(PACKAGE / "__init__.py") | exported_names(PACKAGE / "contract" / "__init__.py")
    out = [HEADER, f"Exported names: {len(exported)}.\n"]
    for path in sorted(PACKAGE.rglob("*.py")):
        relative = path.relative_to(PACKAGE).with_suffix("")
        if path.name in ("__init__.py", "__main__.py") and path.parent == PACKAGE:
            continue
        module = ".".join(("webapp_shell", *relative.parts)).removesuffix(".__init__")
        body = describe_module(path, exported)
        if body:
            summary = first_line(ast.parse(path.read_text()))
            intro = f"{summary}\n\n" if summary else ""
            out.append(f"\n## `{module}`\n\n{intro}" + "\n".join(body) + "\n")
    return "".join(out).rstrip("\n") + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        return 0 if TARGET.exists() and TARGET.read_text() == text else 1
    TARGET.write_text(text)
    print(TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
