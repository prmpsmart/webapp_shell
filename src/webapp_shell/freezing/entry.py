"""The entry point of a frozen program: a file written for each build."""

from ..enums import ShellKind
from .plan import FreezePlan

ENTRY_SOURCE = '''"""Entry point of the frozen {shell} build (generated by webapp_shell.freezing)."""

import multiprocessing
import sys

from webapp_shell import Installation, run
from {module} import {attribute} as target

if __name__ == "__main__":
    multiprocessing.freeze_support()  # a child process of the program is the same executable
    config = target() if callable(target) else target
    args = sys.argv[1:]
    sys.exit(run(config, args if args[:1] and args[0] in Installation.COMMANDS else ["{shell}", *args]))
'''


def entry_source(plan: FreezePlan, kind: ShellKind) -> str:
    module, _, attribute = plan.config.partition(":")
    return ENTRY_SOURCE.format(shell=kind.value, module=module, attribute=attribute)
